// Attack 7: Idempotency Protection Test
// Ensures duplicate deliveries (e.g. from network retries) are processed safely without duplicate side effects.
func TestSecurity_IdempotencyDeduplication(t *testing.T) {
	secret := "production-secret-9999"

	// Mock database of processed event IDs
	processedEvents := make(map[string]bool)
	processingCount := 0

	handler := SecureProductionHandler(secret, func(event map[string]interface{}) error {
		eventID, _ := event["id"].(string)

		// Idempotency check: ignore if already processed
		if processedEvents[eventID] {
			// Already fulfilled, safely ignore duplicate delivery!
			return nil
		}

		processedEvents[eventID] = true
		processingCount++
		return nil
	})

	now := time.Now().Unix()
	timestampStr := strconv.FormatInt(now, 10)
	body := `{"id":"evt_idempotent_123","event":"transaction.status_changed"}`
	sig := computeHMACSHA256(timestampStr+"."+body, secret)

	// Delivery 1 (First attempt)
	req1 := httptest.NewRequest(http.MethodPost, "/webhook", bytes.NewReader([]byte(body)))
	req1.Header.Set("X-Inavate-Timestamp", timestampStr)
	req1.Header.Set("X-Inavate-Signature", sig)
	w1 := httptest.NewRecorder()
	handler(w1, req1)

	if w1.Code != http.StatusOK {
		t.Fatalf("expected 200 OK on first delivery, got %d", w1.Code)
	}

	// Delivery 2 (Duplicate retry from platform)
	req2 := httptest.NewRequest(http.MethodPost, "/webhook", bytes.NewReader([]byte(body)))
	req2.Header.Set("X-Inavate-Timestamp", timestampStr)
	req2.Header.Set("X-Inavate-Signature", sig)
	w2 := httptest.NewRecorder()
	handler(w2, req2)

	if w2.Code != http.StatusOK {
		t.Fatalf("expected 200 OK on duplicate delivery, got %d", w2.Code)
	}

	// Verify that side effects were executed EXACTLY once
	if processingCount != 1 {
		t.Fatalf("expected processingCount to be 1, got %d (idempotency failed)", processingCount)
	}
}

