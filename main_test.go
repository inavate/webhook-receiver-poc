func TestWebhookVerification_Valid(t *testing.T) {
	secret := "test-secret-1234"
	setSecret(secret)

	now := time.Now().Unix()
	timestampStr := strconv.FormatInt(now, 10)
	rawBody := `{"id":"evt_test_1","event":"transaction.status_changed","data":{"status":"completed"}}`

	sigPayload := timestampStr + "." + rawBody
	expectedSig := computeHMACSHA256(sigPayload, secret)

	req := httptest.NewRequest(http.MethodPost, "/webhook", bytes.NewReader([]byte(rawBody)))
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("X-Inavate-Timestamp", timestampStr)
	req.Header.Set("X-Inavate-Signature", expectedSig)

	w := httptest.NewRecorder()
	handleWebhook(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("expected 200 OK, got %d", w.Code)
	}

	var resp map[string]interface{}
	if err := json.NewDecoder(w.Body).Decode(&resp); err != nil {
		t.Fatalf("failed to decode response: %v", err)
	}

	if resp["signature_valid"] != true {
		t.Errorf("expected signature_valid to be true, got %v", resp["signature_valid"])
	}
	if resp["status_detail"] != "verified" {
		t.Errorf("expected status_detail to be verified, got %v", resp["status_detail"])
	}
}

