// Attack 1: Signature Forgery / Spoofing Attack
// Ensures that forged or invalid signatures are REJECTED (HTTP 401) and business logic is NEVER executed.
func TestAttack_ForgedSignature_RejectedAndIgnored(t *testing.T) {
	secret := "production-secret-9999"
	businessLogicExecuted := false

	// Secure production handler with simulated order fulfillment
	handler := SecureProductionHandler(secret, func(event map[string]interface{}) error {
		businessLogicExecuted = true
		return nil
	})

	now := time.Now().Unix()
	timestampStr := strconv.FormatInt(now, 10)
	rawBody := `{"id":"evt_forged_1","event":"transaction.status_changed","data":{"status":"settled"}}`

	// Forged signature generated by attacker without knowledge of the secret
	fakeSignature := "deadbeefcafebabe0123456789abcdef0123456789abcdef0123456789abcdef"

	req := httptest.NewRequest(http.MethodPost, "/webhook", bytes.NewReader([]byte(rawBody)))
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("X-Inavate-Timestamp", timestampStr)
	req.Header.Set("X-Inavate-Signature", fakeSignature)

	w := httptest.NewRecorder()
	handler(w, req)

	// 1. Must return 401 Unauthorized (NOT 200 OK)
	if w.Code != http.StatusUnauthorized {
		t.Fatalf("expected 401 Unauthorized for forged signature, got %d", w.Code)
	}

	// 2. Business logic must be IGNORED / NOT executed
	if businessLogicExecuted {
		t.Fatal("SECURITY BREACH: Business logic was executed on forged webhook!")
	}
}

// Attack 2: Payload Tampering / Man-In-The-Middle Bit-Flip Attack
// Ensures that if an attacker intercepts a legitimate webhook and changes a single byte
// (e.g. changing the transaction amount), the signature verification fails and it is rejected.
func TestAttack_PayloadTampering_BitFlip(t *testing.T) {
	secret := "production-secret-9999"
	businessLogicExecuted := false

	handler := SecureProductionHandler(secret, func(event map[string]interface{}) error {
		businessLogicExecuted = true
		return nil
	})

	now := time.Now().Unix()
	timestampStr := strconv.FormatInt(now, 10)

	// Legitimate payload generated by Inavate
	originalBody := `{"id":"evt_legit_10","amount":10.00,"event":"transaction.created"}`
	legitimateSignature := computeHMACSHA256(timestampStr+"."+originalBody, secret)

	// Attacker tampers with the amount in transit (10.00 -> 9999.00)
	tamperedBody := `{"id":"evt_legit_10","amount":9999.00,"event":"transaction.created"}`

	req := httptest.NewRequest(http.MethodPost, "/webhook", bytes.NewReader([]byte(tamperedBody)))
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("X-Inavate-Timestamp", timestampStr)
	req.Header.Set("X-Inavate-Signature", legitimateSignature) // original signature does NOT match tampered body!

	w := httptest.NewRecorder()
	handler(w, req)

	if w.Code != http.StatusUnauthorized {
		t.Fatalf("expected 401 Unauthorized for tampered payload, got %d", w.Code)
	}
	if businessLogicExecuted {
		t.Fatal("SECURITY BREACH: Tampered payload executed business logic!")
	}
}

